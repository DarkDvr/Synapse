// The project's AGENTS.md: the map every session starts with, and the notepad.
//
// Why this file, and why at the project root: the engine reads `AGENTS.md` from the
// session's directory, so every role — the Architect and every worker — has the map
// in front of it before its first tool call. The fence used to be knowable only by
// trying it: a worker wrote where it thought the file belonged, the engine refused,
// and the model then spent turns going around the refusal or re-orienting. The
// Architect knew no map at all, and composed tasks that crossed another role's
// folder (20 Nov: QC was told to rewrite the design sheet it may not write).
//
// Two parts, one file:
//
//   * the generated block, between two markers. It names the project, the scratch
//     folder, the harness, and one row per role. It is built from the same constants
//     that build the permission rules (OWNED_DIR, SHARED_DIR, EVIDENCE_DIR), so the
//     map cannot drift from the fence it describes.
//   * the notepad below the end marker: the durable facts the Architect keeps. It is
//     never rewritten, never trimmed, and not counted against the map.
//
// **Kept current by comparison, not by a version number.** On boot, on Add Project
// and before a session is created, Synapse regenerates the block and rewrites only
// the block when its text differs from what is in the file. Change the text in a new
// build and every project takes the change on the next open; there is no constant to
// bump and forget, and a model that edited the block is corrected the same way.
//
// It replaces `.project/facts.md`. A facts file found on the way in is folded into
// the notepad and deleted once the new file is written — its content is never
// rewritten, and the header says where facts live now.
import fs from 'node:fs';
import path from 'node:path';

import { ROOT, scratchDir } from './paths.js';

/** Mirrors PLAN_DIR in plans.js — kept here so this module imports no plan code. */
const PLAN_DIR = '.project';

export const AGENTS_NAME = 'AGENTS.md';
/** Project-relative, the form the briefs and the refusal notes use. */
export const AGENTS_RELATIVE = AGENTS_NAME;
/** A screen of facts, not a second document. Past this the Architect condenses. */
export const AGENTS_LIMIT = 6000;

// The markers. Stable on purpose: changing them would orphan every file ever written,
// and an orphaned file is treated as all-notepad (see compose) — their text survives,
// but a doubled header is ugly. If one has to change, the old one is recognised too.
const BEGIN = '<!-- synapse:agents:begin -->';
const END = '<!-- synapse:agents:end -->';

/** Where a role may write inside .project, and nowhere else there. */
export const OWNED_DIR = {
  inventor: `${PLAN_DIR}/ideas`,
  designer: `${PLAN_DIR}/design`,
  qc: `${PLAN_DIR}/qc_findings`,
};

/** A folder every role may write: screenshots the visual-review skill produces. */
export const SHARED_DIR = `${PLAN_DIR}/shots`;

/** The folder every role keeps evidence in, and the brief says so to every role. */
export const EVIDENCE_DIR = `${PLAN_DIR}/reports`;

const agentsPath = (dir) => path.join(String(dir || ''), AGENTS_NAME);

const slash = (value) => String(value || '').replace(/\\/g, '/');

/**
 * The generated block: the map, in the words a model can act on.
 *
 * It is deliberately short. It is loaded at the start of every session of every role,
 * so a paragraph nobody needs is a paragraph paid for on every turn; and it is
 * generated, so every sentence here is one the rules already enforce.
 */
export function headerText(dir, { scratch = '', harness = ROOT } = {}) {
  const root = slash(path.resolve(String(dir || '')) || '.');
  const name = path.basename(String(dir || '')) || 'this project';
  let scratchPath = scratch;
  if (!scratchPath) {
    try {
      scratchPath = scratchDir(dir);
    } catch {
      // A project that cannot resolve a scratch folder still gets its map; the line
      // below then says where scratch is without a path.
      scratchPath = '';
    }
  }
  const scratchLine = scratchPath
    ? `Scratch for probes and throwaway files: \`${slash(scratchPath)}\`.`
    : 'Probe scripts and throwaway files go in the scratch folder the harness gives this project.';
  return [
    BEGIN,
    `# ${name} — how this project works`,
    '',
    'Generated by Synapse. This block is rewritten when the build changes it, so do not',
    'edit it; everything below the end marker is the project\'s own notes.',
    '',
    '**Your fence.** You may read anything in this project. You may write and run in the',
    `project folder \`${root}\` — except \`${PLAN_DIR}/\`, which is the record: one folder per role,`,
    'and nobody writes another role\'s folder. ' +
      scratchLine,
    `\`${slash(harness)}\` (Synapse\'s own folder) is readable, never writable. Anything else`,
    'on this machine asks the operator.',
    '',
    '| role | may write inside .project/ |',
    '|---|---|',
    '| architect | all of it, and this file |',
    '| designer | `.project/design/` — the design sheet and its mocks |',
    '| qc | `.project/qc_findings/` — findings only; QC never edits what it judges |',
    '| inventor | `.project/ideas/` |',
    '| coder-1, coder-2 | nothing of their own |',
    '| every role | `.project/reports/` (evidence) and `.project/shots/` (renders) |',
    '',
    'A refused write inside `.project/` is not a puzzle: write in your own folder, or say in',
    'your report why the file has to be somewhere else. Single mode has no roles — one',
    'chat writes all of it.',
    '',
    '**Project facts** belong below the end marker, in this file — not in `facts.md` or any',
    'other file. The harness folded the old file in; this is the only copy. One dated line',
    'per fact, under its heading.',
    END,
  ].join('\n');
}

/** The notepad a project starts with: the headings, and the rule for using them. */
export function notepadTemplate() {
  return [
    '',
    '# Project facts',
    '',
    'The Architect keeps this section. One dated line per fact, under the heading it',
    'belongs to: what a run taught that will still be true next week — a command that',
    'fails here, a path that resolves oddly, an account or tool the project depends on,',
    `a limit the operator set. Keep it under ${AGENTS_LIMIT} characters: past that,`,
    'condense before adding. Delete a fact that stopped being true instead of writing a',
    'newer one beside it. It is reference, not narrative; the reports hold the story and',
    'the plan holds the work.',
    '',
    '## Stack and layout',
    '',
    '## Outside the project',
    '',
    '## Harness quirks',
    '',
    '## Lessons learned',
    '',
  ].join('\n');
}

/** The block currently in a file, or null when the file has no markers. */
function blockOf(text) {
  const begin = text.indexOf(BEGIN);
  if (begin < 0) return null;
  const end = text.indexOf(END, begin + BEGIN.length);
  if (end < 0) return null;
  return { begin, end: end + END.length };
}

/**
 * The file as it should read now, from the file as it is.
 *
 * Three shapes, and none of them loses a word the project wrote:
 *  - marked: the block is replaced, everything before and after it is kept;
 *  - unmarked (a project's own AGENTS.md, or a marker an edit ate): the block goes
 *    on top and the whole file becomes the notepad;
 *  - missing: the block, then the facts file if there is one, else the template.
 */
export function compose(dir, existing, { scratch = '', harness = ROOT, facts = null } = {}) {
  const header = headerText(dir, { scratch, harness });
  const text = String(existing || '');
  if (!text.trim()) {
    const notepad = facts && String(facts).trim() ? `\n${String(facts).trim()}\n` : notepadTemplate();
    return `${header}\n${notepad}`;
  }
  const block = blockOf(text);
  if (block) {
    return `${text.slice(0, block.begin)}${header}${text.slice(block.end)}`;
  }
  return `${header}\n\n${text.replace(/^\s*\n/, '')}`;
}

/** The notepad part of a file, for the size the brief quotes and the cap it enforces. */
export function notepadOf(text) {
  const body = String(text || '');
  const end = body.indexOf(END);
  return end < 0 ? '' : body.slice(end + END.length);
}

/**
 * Make sure the project has its AGENTS.md, with the block this build generates.
 *
 * Called from `ensureProjectFolders` (boot, discovery, Add Project) and before a
 * session is created, which is what makes a header change in a new build reach every
 * project without anyone opening it. A read and a string compare when nothing
 * changed; a write only when something did.
 *
 * Never throws: a read-only folder still becomes a project the operator can see and
 * fix, the same rule as the plan file.
 */
export function ensureAgents(dir, { scratchRoot = null, harness = ROOT, log = null } = {}) {
  const target = String(dir || '');
  if (!target.trim()) return { path: '', created: false, updated: false, error: 'no project folder' };
  const file = agentsPath(target);
  let scratch = '';
  try {
    scratch = slash(scratchRoot ? scratchDir(target, scratchRoot) : scratchDir(target));
  } catch {
    // The map can be written without a scratch path; the zone checks own that error.
    scratch = '';
  }
  try {
    let existing = '';
    try {
      existing = fs.readFileSync(file, 'utf8');
    } catch {
      // No file is the normal first case: the block and the template are written below.
      existing = '';
    }
    // The facts file is folded in only when the project has no AGENTS.md yet: an
    // existing file's notepad is the record, and re-importing would duplicate it.
    const factsFile = path.join(target, PLAN_DIR, 'facts.md');
    let facts = null;
    if (!existing.trim()) {
      try {
        facts = fs.readFileSync(factsFile, 'utf8');
      } catch {
        // No old facts file: the notepad starts from the template.
        facts = null;
      }
    }
    const next = compose(target, existing, { scratch, harness, facts });
    const changed = next !== existing;
    if (!changed) {
      return { path: file, created: false, updated: false, migrated: false };
    }
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, next, 'utf8');
    // Only after the new file is on disk: a failed write must not cost the notes.
    let migrated = false;
    if (!existing.trim() && facts && String(facts).trim()) {
      try {
        fs.rmSync(factsFile, { force: true });
        migrated = true;
      } catch {
        // A locked facts file is left in place: the content is already in the new
        // file, and deleting it is a tidiness step, not a step the map depends on.
        migrated = false;
      }
    }
    if (migrated) log?.info?.(`project facts moved into ${AGENTS_NAME}: ${path.basename(target)}`);
    return { path: file, created: !existing.trim(), updated: Boolean(existing.trim()), migrated };
  } catch (err) {
    return { path: file, created: false, updated: false, migrated: false, error: err.message };
  }
}

/** How big the notepad is now — the number the Architect's brief quotes. */
export function agentsStatus(dir) {
  if (!String(dir || '').trim()) return { exists: false, chars: 0, lines: 0, over: false };
  try {
    const text = fs.readFileSync(agentsPath(dir), 'utf8');
    const notepad = notepadOf(text).trim();
    return {
      exists: true,
      chars: notepad.length,
      lines: notepad ? notepad.split('\n').length : 0,
      over: notepad.length > AGENTS_LIMIT,
    };
  } catch {
    // No file yet reads the same as an empty one: the brief says it is there to fill,
    // and quotes a size of 0. There is nothing to report to the operator.
    return { exists: false, chars: 0, lines: 0, over: false };
  }
}
